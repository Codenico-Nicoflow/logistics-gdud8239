/** Topics for a role: staff topics for everyone who may open the guide, admin topics only for an admin. */
export function topicsFor(role: string): GuideTopic[] {
  return GUIDE_TOPICS.filter((t) => t.audience === 'staff' || role === 'admin');
}

export function topicText(topic: GuideTopic): string {
  return [topic.title, topic.summary, ...topic.steps, ...(topic.tips ?? []), ...(topic.warnings ?? [])].join(' ');
}
